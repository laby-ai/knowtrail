import assert from 'node:assert/strict';
import { canMoveFolder, folderRows, reparentFolder, deleteFolderKeepingChildren } from '../src/lib/folder-hierarchy';
import type { ProjectFolder } from '../src/types';
const folders: ProjectFolder[] = ['1', '2', '11'].map(id => ({ id, name: id, papers: [], createdAt: '', updatedAt: '' }));
const nested = reparentFolder(folders, '11', '1');
assert.deepEqual(folderRows(nested).map(row => [row.folder.id, row.depth]), [['1', 0], ['11', 1], ['2', 0]]);
assert.deepEqual(folderRows(JSON.parse(JSON.stringify(nested))).find(row => row.folder.id === '11')?.ancestors, ['1']);
assert.equal(canMoveFolder(nested, '1', '11'), false);
assert.equal(canMoveFolder(nested, '11', '11'), false);
assert.equal(canMoveFolder(nested, '11', 'missing'), false);
assert.equal(reparentFolder(nested, '1', '11'), nested);
assert.equal(folderRows(reparentFolder(nested, '11', null)).find(row => row.folder.id === '11')?.depth, 0);
const promoted = deleteFolderKeepingChildren(nested, '1');
assert.equal(promoted.find(folder => folder.id === '11')?.parentId, null);
assert.equal(promoted.length, 2);
const subtree = [...nested, { ...folders[0], id: '111', name: '111', parentId: '11' }];
assert.equal(folderRows(reparentFolder(subtree, '11', '2')).find(row => row.folder.id === '111')?.path, '2 / 11 / 111');
assert.equal(deleteFolderKeepingChildren(subtree, '11').find(folder => folder.id === '111')?.parentId, '1');
assert.deepEqual(folders.map(folder => folder.parentId), [undefined, undefined, undefined]);
const damaged = folders.map(folder => ({ ...folder, parentId: folder.id === '1' ? '11' : folder.id === '11' ? '1' : 'missing' }));
assert.equal(new Set(folderRows(damaged).map(row => row.folder.id)).size, 3);
console.log('PASS: nested movement, serialization, root promotion, cycle/missing-parent rejection, deletion preserves children and legacy/corrupt folders remain visible');
