import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

async function main() {
  const fixture = await mkdtemp(path.join(tmpdir(), 'agent-data-'));
  Object.assign(process.env, { STUDIO_DOCUMENT_STORE_DIR: path.join(fixture, 'documents'), SOURCE_STORE_PATH: path.join(fixture, 'sources.json'), SOURCE_STORE_ADAPTER: 'local-json', ZVEC_STORE_PATH: path.join(fixture, 'zvec'), PAPER_HOST_SESSION_VERIFY_URL: 'https://sms-fixture.invalid/session?provider=knowtrail' });
  for (const key of ['OPENAI_COMPAT_API_KEY', 'ARK_API_KEY', 'OPENAI_API_KEY']) process.env[key] = '';
  const app = createRequire(`${process.cwd()}/package.json`);
  const { NextRequest } = app('next/server');
  const { POST } = app('./src/app/api/data-processing/plan/route.ts');
  const { ingestExtractedSource } = app('./src/lib/ingestion-store.ts');
  const { readGeneratedDataPlan, DataPlanSaveError, isDataPlanInput } = app('./src/lib/research-agent-data.ts');
  const { isResearchToolCall } = app('./src/lib/research-agent-contract.ts');
  const { buildDataProcessingPlan } = app('./src/lib/data-processing-plan.ts');
  globalThis.fetch = async (url, init) => {
    assert(String(url).includes('sms-fixture.invalid'), 'No paid model or external calls');
    return new Headers(init?.headers).get('cookie')?.includes('fixture-valid-a') ? Response.json({ data: { authenticated: true, provider: 'knowtrail', workspaceKey: `paper-user-${'a'.repeat(32)}`, capabilities: ['verified-sms-session'] } }) : Response.json({}, { status: 401 });
  };
  const notebookId = 'agent-data-fixture';
  const input = { sourceId: 'data-source', question: '预测response，仅软件验收，不运行训练。', sampleUnit: '单个患者', taskFamily: 'prediction', targetColumn: 'response', splitColumn: 'site' };
  const rawContent = 'patient_id,site,age,response\np1,A,20,yes\np2,A,,no\np3,B,42,yes\np4,B,37,no';
  await ingestExtractedSource({ id: input.sourceId, title: '软件验收模拟表格', fileName: 'fixture.csv', fileType: 'csv', rawContent, content: rawContent, ownerMemberId: `paper-host:paper-user-${'a'.repeat(32)}`, notebookId });
  assert(isDataPlanInput(input));
  assert(!isDataPlanInput({ ...input, sampleUnit: '' }));
  assert(!isDataPlanInput({ ...input, taskFamily: 'trend', splitColumn: undefined }));
  assert(!isDataPlanInput({ ...input, targetColumn: undefined }));
  assert(!isDataPlanInput({ ...input, account: 'forged' }));
  const runId = '00000000-0000-4000-a000-000000000001';
  const request = (body: unknown) => new NextRequest('https://fixture.invalid/knowtrail/api/data-processing/plan', { method: 'POST', headers: { cookie: 'userId=fixture; token=fixture-valid-a', 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const response = await POST(request({ ...input, runId, notebookId, paper: { id: input.sourceId, rawContent: 'forged' }, persistArtifact: true, expectedRevision: null }));
  assert.equal(response.status, 200);
  const payload = await response.json();
  const signal = new AbortController().signal;
  const saved = await readGeneratedDataPlan(Response.json(payload), runId, input, null, signal);
  assert.equal(saved.data.plan.dataset.rowCount, 4);
  assert.equal(saved.data.plan.dataset.columns.find((c: { name: string }) => c.name === 'age').missingCount, 1);
  assert.deepEqual(saved.data.plan.contract.inputColumns, ['age']);
  for (const changed of [{ ...input, sourceId: 'another' }, { ...input, sampleUnit: '另一单位' }, { ...input, taskFamily: 'description' }, { ...input, targetColumn: 'age' }]) await assert.rejects(readGeneratedDataPlan(Response.json(payload), runId, changed, null, signal));
  await assert.rejects(readGeneratedDataPlan(Response.json(payload), runId.replace(/1$/, '2'), input, null, signal));
  await readGeneratedDataPlan(Response.json({ msg: '保存失败', unsavedDocument: saved.data }, { status: 503 }), runId, input, null, signal).then(() => assert.fail('Unsaved result cannot be durable'), (error: unknown) => assert(error instanceof DataPlanSaveError));
  const reference = { ...input, sourceIds: [input.sourceId], revision: saved.revision, runId, status: 'complete' };
  const call = { id: 'data-1', plugin: 'data-processing', query: input.question, status: 'ready', dataPlan: reference };
  assert(isResearchToolCall(call));
  assert(!isResearchToolCall({ ...call, plugin: 'report' }));
  assert(!isResearchToolCall({ ...call, dataPlan: { ...reference, sourceIds: ['another'] } }));
  const pending = { ...call, status: 'failed', dataPlan: undefined, pendingDataPlan: { ...reference, data: saved.data, expectedRevision: null } };
  assert(isResearchToolCall(pending));
  assert(!isResearchToolCall({ ...pending, status: 'ready' }));
  const wide = buildDataProcessingPlan({ question: '描述缺失', sampleUnit: '模拟记录', taskFamily: 'description' }, { id: 'wide', title: 'wide', fileType: 'csv', rawContent: Array.from({ length: 14 }, (_, n) => 'col' + n).join(',') + '\n' + Array(14).fill('1').join(',') });
  assert.equal(wide.dataset.columnCount, 14); assert.equal(wide.dataset.columns.length, 12);
  assert(wide.dataQuality.warnings.some((s: string) => s.includes('仅诊断前 12 列')));
  const abort = new AbortController(); abort.abort();
  await assert.rejects(readGeneratedDataPlan(Response.json(payload), runId, input, null, abort.signal), { name: 'AbortError' });
  console.log(JSON.stringify({ ok: true, actualPlanAndDurableAck: true, verifiedSourceAndColumns: true, immutableRefs: true, unsavedRetryContract: true, samplingBoundary: true, paidCalls: 0 }));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
